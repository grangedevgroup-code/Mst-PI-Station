#!/usr/bin/env bash
set -euo pipefail

SDR_GAIN="${SDR_GAIN:-40}"          # RTL-SDR gain (0=auto, 40=typical outdoor)
SDR_PPM="${SDR_PPM:-0}"             # Frequency correction in PPM (calibrate with kalibrate-rtl)
SDR_DEVICE_INDEX="${SDR_DEVICE_INDEX:-0}"
DUMP1090_PORT="${DUMP1090_PORT:-30003}"  # BaseStation TCP output port
DUMP1090_HTTP_PORT="${DUMP1090_HTTP_PORT:-8754}"
SDR_ENABLE_DUMP1090="${SDR_ENABLE_DUMP1090:-1}"
SDR_ENABLE_RTL433="${SDR_ENABLE_RTL433:-1}"
REGULATORY_DOMAIN="${REGULATORY_DOMAIN:-}"

# Auto-detect regional ISM frequency for rtl_433
# 433.92 MHz = EU/Asia/AU; 915 MHz = US/CA/MX/BR; 868 MHz = EU alt
RTL433_FREQ="433920000"
if [[ -z "${REGULATORY_DOMAIN}" ]]; then
    TZ=$(timedatectl show --property=Timezone --value 2>/dev/null || cat /etc/timezone 2>/dev/null || echo "")
    case "${TZ}" in
        America/*) REGULATORY_DOMAIN="US" ;;
        Australia/*) REGULATORY_DOMAIN="AU" ;;
        Europe/*) REGULATORY_DOMAIN="DE" ;;
    esac
fi
case "${REGULATORY_DOMAIN:-}" in
    US|CA|MX|BR|AR|CL) RTL433_FREQ="915000000" ;;
    AU|NZ)              RTL433_FREQ="915000000" ;;
    JP|KR)              RTL433_FREQ="920000000" ;;
    CN)                 RTL433_FREQ="433920000" ;;
    *)                  RTL433_FREQ="433920000" ;;  # EU + most of world
esac

log() { echo "[sdr/configure] $*"; }

mkdir -p /etc/aetherium/sdr /var/log/aetherium/sdr
chown -R aetherium:aetherium /var/log/aetherium/sdr 2>/dev/null || true

# rtl_433 config
cat > /etc/aetherium/sdr/rtl_433.conf << CONF
# rtl_433 configuration — Generated by Aetherium
# Decodes 433MHz IoT sensors, weather stations, tire pressure monitors, etc.

frequency ${RTL433_FREQ}
gain ${SDR_GAIN}
ppm_error ${SDR_PPM}
device ${SDR_DEVICE_INDEX}

# Output to JSON log and stdout
output json:/var/log/aetherium/sdr/rtl433.json
output kv

# Protocol decoder groups (uncomment to restrict)
# protocol 1   # Lacrosse TX
# protocol 17  # Acurite weather
# protocol 40  # Ambientweather

# Log level (0=quiet, 1=brief, 2=verbose)
verbose 0
CONF

# rtl_433 start script (device index can be shared with dump1090 via rtl_tcp)
cat > /etc/aetherium/sdr/rtl433-start.sh << 'SCRIPT'
#!/usr/bin/env bash
# If dump1090 is also enabled, use rtl_tcp as a shared source
if systemctl is-active aetherium-dump1090 &>/dev/null; then
    exec rtl_433 -d rtl_tcp:127.0.0.1:1234 -c /etc/aetherium/sdr/rtl_433.conf
else
    exec rtl_433 -c /etc/aetherium/sdr/rtl_433.conf
fi
SCRIPT
chmod +x /etc/aetherium/sdr/rtl433-start.sh

# dump1090 start script
cat > /etc/aetherium/sdr/dump1090-start.sh << SCRIPT
#!/usr/bin/env bash
DUMP1090_BIN=\$(command -v dump1090-fa || command -v dump1090 || echo "")
if [[ -z "\${DUMP1090_BIN}" ]]; then
    echo "[sdr] dump1090 not found" >&2
    exit 1
fi
# Start rtl_tcp first so rtl_433 can share the device
rtl_tcp -d ${SDR_DEVICE_INDEX} -p 1234 -g ${SDR_GAIN} &
RTL_TCP_PID=\$!
sleep 2

exec "\${DUMP1090_BIN}" \
    --net \
    --net-ro-port ${DUMP1090_PORT} \
    --net-http-port ${DUMP1090_HTTP_PORT} \
    --gain ${SDR_GAIN} \
    --ppm ${SDR_PPM} \
    --write-json /var/log/aetherium/sdr \
    --quiet
SCRIPT
chmod +x /etc/aetherium/sdr/dump1090-start.sh

# Enable/start services based on config
if [[ "${SDR_ENABLE_DUMP1090}" == "1" ]] && command -v dump1090 &>/dev/null || command -v dump1090-fa &>/dev/null 2>/dev/null; then
    systemctl enable aetherium-dump1090 2>/dev/null || true
    systemctl restart aetherium-dump1090 || true
fi

if [[ "${SDR_ENABLE_RTL433}" == "1" ]] && command -v rtl_433 &>/dev/null; then
    systemctl enable aetherium-rtl433 2>/dev/null || true
    systemctl restart aetherium-rtl433 || true
fi

log "SDR configured"
[[ "${SDR_ENABLE_DUMP1090}" == "1" ]] && log "ADS-B map: http://aetherium.local:${DUMP1090_HTTP_PORT}"
log "rtl_433 sensor log: /var/log/aetherium/sdr/rtl433.json"
