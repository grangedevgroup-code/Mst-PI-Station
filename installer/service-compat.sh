#!/usr/bin/env bash
# Service compatibility layer — converts systemd .service files to procd init.d scripts.
# Run automatically on OpenWrt (INIT_SYSTEM=procd) after module installation.
# Safe no-op on systemd/openrc systems.

[[ -f /etc/aetherium/distro.env ]] && source /etc/aetherium/distro.env
INIT_SYSTEM="${INIT_SYSTEM:-systemd}"

[[ "${INIT_SYSTEM}" != "procd" ]] && exit 0

log() { echo "[service-compat] $*"; }
log "Converting systemd service files to procd init.d scripts..."

AETHERIUM_DIR="${AETHERIUM_DIR:-/opt/aetherium}"

convert_service() {
    local svc_file="$1"
    local svc_name
    svc_name=$(basename "${svc_file}" .service)

    # Parse key fields from the .service file
    local exec_start description user after wants
    exec_start=$(awk -F= '/^ExecStart=/{print $2; exit}' "${svc_file}" | xargs)
    description=$(awk -F= '/^Description=/{print $2; exit}' "${svc_file}" | xargs)
    user=$(awk -F= '/^User=/{print $2; exit}' "${svc_file}" | xargs)
    user="${user:-root}"

    [[ -z "${exec_start}" ]] && { log "Skipping ${svc_name} — no ExecStart"; return; }

    local init_script="/etc/init.d/${svc_name}"
    cat > "${init_script}" << SCRIPT
#!/bin/sh /etc/rc.common
# ${description:-${svc_name}} — auto-generated by Aetherium service-compat.sh
USE_PROCD=1
START=90
STOP=10

start_service() {
    procd_open_instance
    procd_set_param command ${exec_start}
    procd_set_param respawn 3600 5 0
    procd_set_param user ${user}
    procd_set_param stdout 1
    procd_set_param stderr 1
    procd_close_instance
}

reload_service() {
    restart
}
SCRIPT
    chmod +x "${init_script}"
    log "  ${svc_name} → ${init_script}"
}

# Convert all aetherium-*.service files
CONVERTED=0
for svc in /etc/systemd/system/aetherium-*.service \
           /lib/systemd/system/aetherium-*.service; do
    [[ -f "${svc}" ]] || continue
    convert_service "${svc}"
    CONVERTED=$((CONVERTED + 1))
done

# Also convert reticulum.service and other known non-prefixed services
for svc in /etc/systemd/system/reticulum.service \
           /etc/systemd/system/batman-adv.service; do
    [[ -f "${svc}" ]] || continue
    convert_service "${svc}"
    CONVERTED=$((CONVERTED + 1))
done

log "Converted ${CONVERTED} service files for procd"
log "Enable services with: /etc/init.d/<name> enable && /etc/init.d/<name> start"
