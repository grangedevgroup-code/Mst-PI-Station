#!/usr/bin/env bash
# Generate a procd-compatible /etc/init.d/<service> script from parameters.
# Usage: write-procd-service.sh <name> <description> <exec_start> [user] [restart_on_failure]
#
# This is used on OpenWrt instead of systemd .service files.
# Called from module install.sh scripts on INIT_SYSTEM=procd systems.

SERVICE_NAME="$1"
SERVICE_DESC="${2:-Mst-PI-Station ${1}}"
EXEC_START="$3"
SERVICE_USER="${4:-root}"
RESTART="${5:-1}"

[[ -z "${SERVICE_NAME}" ]] && { echo "Usage: write-procd-service.sh <name> <desc> <exec> [user] [restart]" >&2; exit 1; }

INIT_SCRIPT="/etc/init.d/${SERVICE_NAME}"

cat > "${INIT_SCRIPT}" << SCRIPT
#!/bin/sh /etc/rc.common
# ${SERVICE_DESC} — generated by Mst-PI-Station write-procd-service.sh
# Do not edit — re-generated on mstpistation deploy

USE_PROCD=1
START=90
STOP=10

start_service() {
    procd_open_instance
    procd_set_param command ${EXEC_START}
    procd_set_param respawn ${RESTART} 5 0
    procd_set_param user ${SERVICE_USER}
    procd_set_param stdout 1
    procd_set_param stderr 1
    procd_close_instance
}

reload_service() {
    restart
}
SCRIPT

chmod +x "${INIT_SCRIPT}"
echo "[installer] Procd init script written: ${INIT_SCRIPT}"
