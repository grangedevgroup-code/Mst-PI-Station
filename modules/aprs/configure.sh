#!/usr/bin/env bash
set -euo pipefail

NODE_NAME="${NODE_NAME:-AETH}"
APRS_CALLSIGN="${APRS_CALLSIGN:-N0CALL}"   # Set in mstpistation.yaml: aprs.callsign
APRS_SSID="${APRS_SSID:-9}"                # 9 = mobile, 0 = fixed station
APRS_SYMBOL="${APRS_SYMBOL:-/[}"           # laptop symbol — change to /#& for digipeater
APRS_COMMENT="${APRS_COMMENT:-Mst-PI-Station Mesh Node}"
APRS_PATH="${APRS_PATH:-WIDE1-1,WIDE2-1}"
APRS_RX_ONLY="${APRS_RX_ONLY:-1}"         # 1=receive only, 0=transmit (requires license)

# Audio device detection
AUDIO_DEV="default"
if command -v aplay &>/dev/null; then
    AUDIO_DEV=$(aplay -l 2>/dev/null | grep -i "card" | head -1 | awk '{print "plughw:"$2$3}' | tr -d ',' || echo "default")
fi

# Load APRS config from site config
if [[ -f /etc/mstpistation/mstpistation.yaml ]]; then
    APRS_CALLSIGN=$(python3 -c "
import yaml
cfg = yaml.safe_load(open('/etc/mstpistation/mstpistation.yaml'))
print(cfg.get('aprs', {}).get('callsign', 'N0CALL'))
" 2>/dev/null || echo "N0CALL")
fi

log() { echo "[aprs/configure] $*"; }

# Determine PTT method
PTT_LINE=""
if [[ "${APRS_RX_ONLY}" != "1" ]]; then
    # GPIO PTT for Pi (GPIO 17 = pin 11)
    if [[ -d /sys/class/gpio ]]; then
        PTT_LINE="PTT GPIO 17"
    fi
fi

# Get GPS location for beacon
LAT="0000.00N"
LON="00000.00W"
if [[ -f /var/lib/mstpistation/location.json ]]; then
    GPS_DATA=$(cat /var/lib/mstpistation/location.json)
    LAT_DEG=$(echo "${GPS_DATA}" | python3 -c "import json,sys; d=json.load(sys.stdin); lat=d.get('lat',0); print(f'{abs(lat):07.2f}{\"N\" if lat>=0 else \"S\"}')" 2>/dev/null || echo "0000.00N")
    LON_DEG=$(echo "${GPS_DATA}" | python3 -c "import json,sys; d=json.load(sys.stdin); lon=d.get('lon',0); print(f'{abs(lon):08.2f}{\"E\" if lon>=0 else \"W\"}')" 2>/dev/null || echo "00000.00W")
    LAT="${LAT_DEG}"
    LON="${LON_DEG}"
fi

cat > /etc/mstpistation/aprs/direwolf.conf << CONF
# Direwolf configuration — Generated by Mst-PI-Station
# WARNING: Transmitting APRS requires an amateur radio license.
# Set APRS_RX_ONLY=0 in mstpistation.yaml to enable transmit.

# Audio device
ADEVICE ${AUDIO_DEV}
CHANNEL 0

# Callsign (set your actual callsign in mstpistation.yaml: aprs.callsign)
MYCALL ${APRS_CALLSIGN}-${APRS_SSID}

# Modem
MODEM 1200

# AGW TCPIP server (for connecting APRS clients)
AGWPORT 8000

# KISS TCP port (for connecting other TNC software)
KISSPORT 8001

# Receive-only mode: ${APRS_RX_ONLY}
$([ "${APRS_RX_ONLY}" = "1" ] && echo "# Transmit disabled (receive-only mode)" || echo "${PTT_LINE}")

# Beacon (only active when not in receive-only mode)
$([ "${APRS_RX_ONLY}" != "1" ] && cat << BEACON
PBEACON delay=1 every=30 symbol="${APRS_SYMBOL}" \\
    lat=${LAT} long=${LON} \\
    comment="${APRS_COMMENT}" \\
    via=${APRS_PATH}
BEACON
)

# IGate — forward received packets to APRS-IS internet server (if uplink available)
# Uncomment and set your callsign to enable IGate:
# IGSERVER noam.aprs2.net
# IGLOGIN ${APRS_CALLSIGN} <passcode>

# Log received packets
LOGDIR /var/log/mstpistation/aprs
CONF

if [[ "${APRS_CALLSIGN}" == "N0CALL" ]]; then
    log "WARNING: Set your callsign in /etc/mstpistation/mstpistation.yaml: aprs.callsign"
    log "APRS transmit requires an amateur radio license."
fi

systemctl enable mstpistation-direwolf 2>/dev/null || true
systemctl restart mstpistation-direwolf || true

sleep 2
if systemctl is-active mstpistation-direwolf &>/dev/null; then
    log "Direwolf APRS TNC running"
    log "AGW port: 8000 (connect APRS clients)"
    log "KISS port: 8001 (connect TNC software)"
    log "Callsign: ${APRS_CALLSIGN}-${APRS_SSID}"
fi
